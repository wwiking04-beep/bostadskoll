export function hittaKo(slug) {
  return KOER.find((k) => k.slug === slug);
}

// Nästa frist och dagar kvar för en bevakning.
export function frist(senastAtgard, intervallDagar, idag = new Date()) {
  const d = new Date(senastAtgard + 'T00:00:00');
  d.setDate(d.getDate() + intervallDagar);
  const noll = new Date(idag.getFullYear(), idag.getMonth(), idag.getDate());
  const dagar = Math.round((d - noll) / 86400000);
  return { datum: d, dagarKvar: dagar };
}
